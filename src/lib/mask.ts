// LLM 제공사로 보내기 전에 개인정보 패턴을 가린다. 완벽하지 않으므로 사용자 고지와 함께 쓴다.
// 주민번호를 먼저 처리해야 전화번호 규칙에 부분 일치하지 않는다.
const RULES: Array<[RegExp, string]> = [
  [/\d{6}-?[1-4]\d{6}/g, "[주민번호]"],
  [/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, "[이메일]"],
  [/(?:\+82[-\s]?)?0?1[016789][-.\s]?\d{3,4}[-.\s]?\d{4}/g, "[전화번호]"],
  [/0\d{1,2}[-.\s]\d{3,4}[-.\s]\d{4}/g, "[전화번호]"],
];

export const maskPii = (text: string) => RULES.reduce((t, [re, label]) => t.replace(re, label), text);
